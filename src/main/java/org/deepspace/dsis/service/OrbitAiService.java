package org.deepspace.dsis.service;

import org.deepspace.dsis.model.AnomalyRecord;
import org.deepspace.dsis.model.Mission;
import org.deepspace.dsis.model.Spacecraft;
import org.deepspace.dsis.repository.AnomalyRecordRepository;
import org.deepspace.dsis.repository.MissionRepository;
import org.deepspace.dsis.repository.SpacecraftRepository;
import org.springframework.stereotype.Service;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.*;

@Service
public class OrbitAiService {

    private final SpacecraftRepository spacecraftRepository;
    private final AnomalyRecordRepository anomalyRepository;
    private final MissionRepository missionRepository;

    public OrbitAiService(SpacecraftRepository spacecraftRepository,
                          AnomalyRecordRepository anomalyRepository,
                          MissionRepository missionRepository) {
        this.spacecraftRepository = spacecraftRepository;
        this.anomalyRepository = anomalyRepository;
        this.missionRepository = missionRepository;
    }

    public Map<String, Object> askOrbit(String prompt) {
        String clean = (prompt != null) ? prompt.trim().toLowerCase() : "";
        Map<String, Object> response = new HashMap<>();
        response.put("timestamp", LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE_TIME));
        response.put("assistant", "ORBIT AI - DSIS Mission Knowledge & Telemetry Specialist");

        // 1. Spacecraft Telemetry Queries
        if (clean.contains("mars explorer") || (clean.contains("mars") && clean.contains("status"))) {
            return spacecraftQuery("Mars Explorer");
        } else if (clean.contains("europa explorer") || (clean.contains("europa") && clean.contains("status"))) {
            return spacecraftQuery("Europa Explorer");
        } else if (clean.contains("titan explorer") || (clean.contains("titan") && clean.contains("status"))) {
            return spacecraftQuery("Titan Explorer");
        } else if (clean.contains("deep space voyager") || clean.contains("voyager")) {
            return spacecraftQuery("Deep Space Voyager");
        } else if (clean.contains("spacecraft") && (clean.contains("all") || clean.contains("list") || clean.contains("summary") || clean.contains("status"))) {
            return allSpacecraftSummary();
        }

        // 2. Anomaly Queries
        if (clean.contains("anomaly") || clean.contains("anomalies") || clean.contains("alert") || clean.contains("alarm")) {
            return anomalyQuery();
        }

        // 3. Emergency & Checklist Queries
        if (clean.contains("emergency") || clean.contains("depressurization") || clean.contains("checklist") || clean.contains("pressure drop") || clean.contains("fire") || clean.contains("oxygen failure")) {
            return emergencyChecklistQuery(clean);
        }

        // 4. Mission Queries
        if (clean.contains("mission") || clean.contains("missions") || clean.contains("launch") || clean.contains("ares")) {
            return missionQuery();
        }

        // 5. Planetary Science Queries
        if (clean.contains("europa") && (clean.contains("ocean") || clean.contains("water") || clean.contains("life") || clean.contains("ice"))) {
            response.put("text", "Europa, the sixth-closest moon of Jupiter, is one of the most compelling astrobiological targets in the Solar System. Beneath its 15-25 km thick fractured water-ice crust lies a global saline subsurface ocean containing approximately 2 to 3 times the volume of all Earth's oceans combined.\n\n" +
                    "• **Heat Source**: Driven by tidal flexure from gravitational orbital resonance with Io and Ganymede (Laplace resonance).\n" +
                    "• **Hydrothermal Activity**: Likely possesses seafloor hydrothermal vents providing geochemical energy (chemosynthesis) in the absence of sunlight.\n" +
                    "• **Atmosphere**: Extremely tenuous molecular oxygen atmosphere generated by radiolytic radiolysis of ice molecules.");
            response.put("category", "Astrobiology & Planetary Geology");
            return response;
        }

        if (clean.contains("titan") && (clean.contains("lake") || clean.contains("methane") || clean.contains("atmosphere"))) {
            response.put("text", "Titan is Saturn's largest moon and the only moon in the Solar System possessing a dense, substantial atmosphere (surface pressure ~1.45 bar, 95% nitrogen, 5% methane).\n\n" +
                    "• **Hydrological Cycle**: Titan hosts a complete liquid cycle analogous to Earth's water cycle, but operating with liquid methane and ethane at cryogenic temperatures (-179°C).\n" +
                    "• **Surface Features**: Vast hydrocarbon seas such as Kraken Mare, Ligeia Mare, and Punga Mare; expansive organic sand dunes; and cryovolcanic flows.");
            response.put("category", "Planetary Science");
            return response;
        }

        if (clean.contains("hohmann") || clean.contains("transfer") || clean.contains("trajectory")) {
            response.put("text", "A **Hohmann Transfer Orbit** is an elliptical orbital maneuver used to transfer a spacecraft between two circular orbits of different radii around a central gravitational body.\n\n" +
                    "• **First Delta-V Burn**: Prograde burn at periapsis of the transfer ellipse to raise apoapsis to match the target orbit's radius.\n" +
                    "• **Coasting Arc**: Spacecraft travels along the Keplerian semi-ellipse under zero propellant consumption.\n" +
                    "• **Second Delta-V Burn**: Prograde burn at apoapsis to circularize the orbit at the target radius.\n" +
                    "• **Delta-V Equation**: Δv₁ = √(μ/r₁) * (√(2r₂/(r₁+r₂)) - 1), where μ is the standard gravitational parameter.");
            response.put("category", "Astrodynamics & Orbital Mechanics");
            return response;
        }

        if (clean.contains("lagrange") || clean.contains("l2") || clean.contains("l1")) {
            response.put("text", "Lagrange points are positions in orbital configuration of two large bodies where the gravitational forces and the centrifugal force balance each other.\n\n" +
                    "• **L1 (Sun-Earth)**: Ideal for solar observation (e.g., SOHO, DSCOVR).\n" +
                    "• **L2 (Sun-Earth)**: Ideal for deep space observatories shielded from Earth and Sun light (e.g., James Webb Space Telescope JWST, Gaia).\n" +
                    "• **L4 & L5**: Stable equilibrium points leading and trailing the secondary body by 60° (Trojan asteroids).");
            response.put("category", "Orbital Mechanics");
            return response;
        }

        // Default Intelligent Fallback
        response.put("text", "Greetings, Operator. I am **ORBIT AI**, your integrated DSIS intelligence assistant. I am continuously linked to our active telemetry buses, anomaly detection matrix, and mission logs.\n\n" +
                "You can query me for:\n" +
                "• Live spacecraft condition: *'Status of Europa Explorer'* or *'Check Mars telemetry'*\n" +
                "• Anomaly assessments: *'List active anomalies'* or *'Explain cryogenic thermal spike'*\n" +
                "• Emergency protocols: *'Show checklist for cabin depressurization'*\n" +
                "• Astrodynamics & Space Science: *'Explain Hohmann transfer orbits'* or *'Subsurface oceans on Europa'*\n\n" +
                "*Note: All spacecraft telemetry and anomaly records represent simulated mission data within the DSIS environment.*");
        response.put("category", "General Assistance");
        return response;
    }

    private Map<String, Object> spacecraftQuery(String name) {
        Map<String, Object> res = new HashMap<>();
        Optional<Spacecraft> opt = spacecraftRepository.findByName(name);
        if (opt.isPresent()) {
            Spacecraft sc = opt.get();
            res.put("text", String.format(
                    "**%s** [%s] Telemetry Diagnostics:\n\n" +
                    "• **Condition**: %s\n" +
                    "• **Target Destination**: %s\n" +
                    "• **Internal Temperature**: %.1f°C (Nominal: -25°C to +45°C)\n" +
                    "• **Cabin Atmospheric Pressure**: %.1f kPa (Nominal: 95.0 to 105.0 kPa)\n" +
                    "• **O2 Concentration**: %.1f%% (Nominal: 19.5%% to 23.5%%)\n" +
                    "• **Main EPS Battery**: %.1f%% | Solar Array: %.0f W\n" +
                    "• **Communications**: %s (SNR: %.1f dB, Latency: %d ms, Downlink: %.0f kbps)\n" +
                    "• **Simulation Engine**: %s (Anomaly Injection: %s)\n\n" +
                    "*Data validated against DSIS Telemetry Bus.*",
                    sc.getName(), sc.getCode(), sc.getStatus(), sc.getTarget(),
                    sc.getTemperature(), sc.getCabinPressure(), sc.getOxygenLevel(),
                    sc.getBatteryLevel(), sc.getSolarArrayOutput(),
                    sc.getCommunicationStatus(), sc.getSnrDb(), sc.getUplinkLatencyMs(), sc.getDownlinkThroughputKbps(),
                    sc.isSimulationActive() ? "ONLINE / STREAMING" : "PAUSED",
                    sc.isAnomalyTriggered() ? sc.getActiveAnomalyType() : "NONE"
            ));
            res.put("spacecraft", sc);
            res.put("category", "Live Telemetry Telemetry");
        } else {
            res.put("text", "Spacecraft '" + name + "' not located in active registry.");
            res.put("category", "Error");
        }
        return res;
    }

    private Map<String, Object> allSpacecraftSummary() {
        Map<String, Object> res = new HashMap<>();
        List<Spacecraft> list = spacecraftRepository.findAll();
        StringBuilder sb = new StringBuilder("**DSIS Active Fleet Status Overview:**\n\n");
        for (Spacecraft sc : list) {
            sb.append(String.format("• **%s** (%s) - Status: **%s** | Temp: %.1f°C | Pressure: %.1f kPa | Battery: %.1f%%\n",
                    sc.getName(), sc.getTarget(), sc.getStatus(), sc.getTemperature(), sc.getCabinPressure(), sc.getBatteryLevel()));
        }
        sb.append("\n*All telemetry feeds are simulated educational streams running on the DSIS engine.*");
        res.put("text", sb.toString());
        res.put("fleetCount", list.size());
        res.put("category", "Fleet Overview");
        return res;
    }

    private Map<String, Object> anomalyQuery() {
        Map<String, Object> res = new HashMap<>();
        List<AnomalyRecord> open = anomalyRepository.findByStatus("OPEN");
        StringBuilder sb = new StringBuilder();
        if (open.isEmpty()) {
            sb.append("No active unacknowledged anomalies currently flagged across the fleet. All telemetry channels are operating within nominal tolerance limits.");
        } else {
            sb.append(String.format("**%d Active Anomaly Alert(s) Detected:**\n\n", open.size()));
            for (AnomalyRecord ar : open) {
                sb.append(String.format("• **[%s] %s**: %s (Measured: %.1f, Expected: %s)\n  *Rationale*: %s\n",
                        ar.getSeverity(), ar.getSpacecraftName(), ar.getParameter(), ar.getMeasuredValue(), ar.getExpectedRange(), ar.getExplanation()));
            }
        }
        res.put("text", sb.toString());
        res.put("activeCount", open.size());
        res.put("category", "AI Anomaly Diagnostic");
        return res;
    }

    private Map<String, Object> emergencyChecklistQuery(String clean) {
        Map<String, Object> res = new HashMap<>();
        res.put("text", "**Educational Emergency Protocol: Cabin Depressurization & ECLSS Failure**\n\n" +
                "1. **Immediate Personal Life Safety**: Don emergency pressure suit helmets immediately and verify oxygen umbilical lock (Target: < 45 seconds).\n" +
                "2. **Compartment Isolation**: Seal inter-module pressure hatches 2A and 3B to localize hull breach.\n" +
                "3. **Telemetry Diagnostics**: Verify cabin pressure descent rate on ECLSS console (kPa/sec).\n" +
                "4. **Emergency Gas Injection**: Trigger secondary N2/O2 quick-release repressurization bottles.\n" +
                "5. **Hull Breach Patching**: Deploy acoustic leak-detection probe and apply rapid curing elastomeric sealant patch.\n\n" +
                "*DISCLAIMER: This emergency checklist is an educational simulation procedure designed for computer science demonstration and does not constitute real-world flight operations certified instructions.*");
        res.put("category", "Emergency Simulator Guidance");
        return res;
    }

    private Map<String, Object> missionQuery() {
        Map<String, Object> res = new HashMap<>();
        List<Mission> missions = missionRepository.findAll();
        StringBuilder sb = new StringBuilder("**Active Mission Directory:**\n\n");
        for (Mission m : missions) {
            sb.append(String.format("• **%s** (%s) - Target: %s | Status: **%s** | Progress: %d%%\n  *Objective*: %s\n",
                    m.getName(), m.getCodeName(), m.getTargetBody(), m.getStatus(), m.getProgressPercentage(), m.getObjective()));
        }
        res.put("text", sb.toString());
        res.put("count", missions.size());
        res.put("category", "Mission Directory");
        return res;
    }
}
